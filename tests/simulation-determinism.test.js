// The main route on the isolated spine: the side zones stay in the world, cut off at their links, with
// their idle monsters, caches and shrine. A side monster that touched the shared random stream
// would change these hashes. The spur beside the road is the only main-path change (seed 5 fights
// a wanderer next to it); the full clear below runs on the real world.
const inLink = p => Object.values(SIDE_LINKS).some(([x0, x1, y0, y1]) => p.x >= x0 && p.x <= x1 && p.y >= y0 && p.y <= y1);
const oldSpine = game => { game.world = { ...game.world, tiles: game.world.tiles.filter(p => !inLink(p)) }; };
// The cache and shrine lists add four fields (world-expansion §6.2). The main-path checkpoints
// ignore exactly these, and the side zones' monsters:
// 1. `cache` on a 'secret' event and on the effect drawn from it;
// 2. `shrine` on a 'heal' event and on its effect;
// 3. adventure.cachesFound;
// 4. game.shrinesUsed, which no checkpoint covers.
const spineView = {
  enemy: e => e.zoneId !== 'cemetery' && e.zoneId !== 'orchard',
  event: e => e.type === 'secret' ? (({ cache, ...rest }) => rest)(e) : e.type === 'heal' ? (({ shrine, ...rest }) => rest)(e) : e,
  adventure: ({ cachesFound, ...rest }) => rest,
};

for (const expected of baseline) test(`the main route keeps the expanded-world checkpoints beside the idle side zones for seed ${expected.seed}`, () => {
  const actual = runSimulationRoute({ ...gameApi, CAMP_SUPPLIES }, expected.seed, { prepare: oldSpine, view: spineView });
  assert.equal(actual.phase, 'victory');
  assert.equal(actual.quest, 'complete');
  assert.equal(actual.kills, actual.monsters);
  assert.ok(actual.wanderers > 0);
  assert.deepEqual(actual, expected);
});

// The same route on the isolated spine alone: no side monsters, no cache and shrine lists, no spur and
// no breach. Nothing is ignored here: every checkpoint equals the old one bit for bit.
const spineOnly = game => {
  const { caches, shrines, ...world } = game.world;
  game.world = { ...world, tiles: world.tiles.filter(p => !inLink(p)) };
  game.enemies = game.enemies.filter(spineView.enemy);
  delete game.adventure.cachesFound; delete game.shrinesUsed;
};

for (const expected of baseline) test(`the isolated spine alone replays the expanded-world checkpoints for seed ${expected.seed}`, () => {
  assert.deepEqual(runSimulationRoute({ ...gameApi, CAMP_SUPPLIES }, expected.seed, { prepare: spineOnly }), expected);
});

